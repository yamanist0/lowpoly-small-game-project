export const districtCount=colors.length*regions.length;
export const districtColumns=Math.ceil(Math.sqrt(districtCount));
export const districtRows=Math.ceil(districtCount/districtColumns);
const offsetX=Math.floor(districtColumns/2),offsetZ=Math.floor(districtRows/2);
const nameOrder=Array.from({length:districtCount},(_,i)=>i);
let nameSeed=0x49a72f19;
for(let i=nameOrder.length-1;i>0;i--){nameSeed=(Math.imul(nameSeed,1664525)+1013904223)>>>0;const j=nameSeed%(i+1);[nameOrder[i],nameOrder[j]]=[nameOrder[j],nameOrder[i]];}
export function districtIndex(ix:number,iz:number){
 const col=ix+offsetX,row=iz+offsetZ;
 if(col<0||col>=districtColumns||row<0||row>=districtRows)return -1;
 const index=row*districtColumns+col;return index<districtCount?index:-1;
}
export function districtName(ix:number,iz:number){
 const index=districtIndex(ix,iz);if(index<0)return null;
 const n=nameOrder[index];return `${colors[Math.floor(n/regions.length)]} ${regions[n%regions.length]}`;
}
// Distance in tile coordinates to the edge of this connected district grid.
export function boundaryDistance(x:number,z:number,spacing:number){
 const ix=Math.round(x/spacing),iz=Math.round(z/spacing);
 if(districtIndex(ix,iz)<0)return -1;
 const dx=x-ix*spacing,dz=z-iz*spacing,half=spacing/2;let distance=Infinity;
 if(districtIndex(ix-1,iz)<0)distance=Math.min(distance,half+dx);
 if(districtIndex(ix+1,iz)<0)distance=Math.min(distance,half-dx);
 if(districtIndex(ix,iz-1)<0)distance=Math.min(distance,half+dz);
 if(districtIndex(ix,iz+1)<0)distance=Math.min(distance,half-dz);
 return distance;
}
